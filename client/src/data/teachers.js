export const getTeacherById = (id) => teachers.find(t => t.id === id);

export const getAdjacentTeachers = (id) => {
  const teacherList = teachers.filter(t => !t.featured);
  const i = teacherList.findIndex(t => t.id === id);
  if (i === -1) return { prev: null, next: null };
  return {
    prev: i > 0 ? teacherList[i - 1] : teacherList[teacherList.length - 1],
    next: i < teacherList.length - 1 ? teacherList[i + 1] : teacherList[0]
  };
};
